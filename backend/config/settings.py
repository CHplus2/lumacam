def _csv(name, default=''):
    """Comma-separated env var -> list, tolerant of spaces, blanks and pasted URLs."""
    items = []
    for raw in os.environ.get(name, default).split(','):
        item = raw.strip().rstrip('/')
        if item:
            items.append(item)
    return items


